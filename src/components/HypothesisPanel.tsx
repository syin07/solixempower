"use client";

// Repurposing hypothesis cards (docs/KG_PRD.md §3 step 6, KG_PLAN M3). Each card is a code-generated
// path through the evidence graph: status chip, the evidence ladder (one row per kind, never summed),
// the suggested test, the path's edges (click → edge drawer) and source chips. Hovering a card
// highlights its path in the graph; clicking pins the highlight.
import { useState } from "react";
import type { GraphEdge, GraphResult, Hypothesis, LadderRow, SourceRef } from "@/lib/contracts";
import { EvidenceBadge } from "./EvidenceBadge";
import { SourceChips } from "./SourceChips";

export const STATUS: Record<Hypothesis["status"], { label: string; className: string }> = {
  proposed: { label: "Proposed", className: "border-emerald-600 bg-white text-emerald-800" },
  already_tested: { label: "Already tested", className: "border-amber-500 bg-amber-50 text-amber-900" },
  already_indicated: { label: "Already indicated", className: "border-zinc-400 bg-zinc-100 text-zinc-700" },
};

export const TEMPLATE: Record<Hypothesis["template"], string> = {
  target_hop: "target hop",
  off_target_hop: "off-target hop",
  comparator_hop: "comparator hop",
  route_hop: "formulation / route",
};

/** Edge type → short word for the path chips. */
const STEP: Record<string, string> = {
  measured_against: "measured",
  mechanism: "mechanism",
  associated_with: "Open Targets",
  indicated_for: "indication",
  tested_in: "trial",
  for_disease: "trial for",
  absent: "not found",
};

const ORDERING_NOTE = "Ordered by status, then genetic evidence, then clinical score; never summed.";

export function StatusChip({ status }: { status: Hypothesis["status"] }) {
  const s = STATUS[status];
  return <span className={`shrink-0 rounded-full border px-2 py-0.5 text-[11px] font-semibold uppercase tracking-wide ${s.className}`}>{s.label}</span>;
}

/** EvidenceBadge, plus the graph-only "absent" kind (checked, not found). */
export function LadderBadge({ kind }: { kind: LadderRow["kind"] }) {
  if (kind !== "absent") return <EvidenceBadge kind={kind} />;
  return (
    <span className="inline-flex shrink-0 items-center rounded border border-dashed border-red-600 bg-red-50 px-1.5 py-0.5 text-[11px] font-semibold uppercase tracking-wide text-red-700">
      Not found
    </span>
  );
}

export function HypothesisPanel({
  hypotheses,
  graph,
  sources,
  pinnedId,
  onHover,
  onPin,
  onSelectEdge,
  expanded = false,
}: {
  hypotheses: Hypothesis[];
  /** For resolving path edge ids to edges and node labels */
  graph: GraphResult;
  sources: Map<string, SourceRef>;
  pinnedId?: string | null;
  onHover: (id: string | null) => void;
  onPin?: (id: string | null) => void;
  onSelectEdge?: (edge: GraphEdge) => void;
  /** The graph was expanded after the hypotheses were generated */
  expanded?: boolean;
}) {
  return (
    <div className="flex flex-col gap-2">
      <div className="flex items-baseline justify-between gap-2">
        <h3 className="font-semibold text-zinc-900">Repurposing hypotheses</h3>
        <span title={ORDERING_NOTE} className="cursor-help text-xs text-zinc-500 underline decoration-dotted">
          how are these ordered?
        </span>
      </div>
      <p className="text-xs text-zinc-500">
        Generated by code from graph paths: each is a traceable gap in public evidence, not a prediction of efficacy.
        {expanded && " Computed on the initial graph; expanded nodes add context but are not gap-checked."}
      </p>
      {hypotheses.length === 0 ? (
        <div className="rounded-md border border-dashed border-zinc-300 bg-zinc-50 p-4 text-sm text-zinc-500">
          No repurposing gap found within two hops; expand a target or disease to look further.
        </div>
      ) : (
        // Scrolls on its own so a long list never pushes the page far below the graph
        <ol className="flex flex-col gap-2 lg:max-h-[1100px] lg:overflow-y-auto lg:pr-1">
          {hypotheses.map((h, i) => (
            <HypothesisCard
              key={h.id}
              h={h}
              graph={graph}
              sources={sources}
              pinned={pinnedId === h.id}
              defaultOpen={i === 0}
              onHover={onHover}
              onPin={onPin}
              onSelectEdge={onSelectEdge}
            />
          ))}
        </ol>
      )}
    </div>
  );
}

function HypothesisCard({
  h,
  graph,
  sources,
  pinned,
  defaultOpen,
  onHover,
  onPin,
  onSelectEdge,
}: {
  h: Hypothesis;
  graph: GraphResult;
  sources: Map<string, SourceRef>;
  pinned: boolean;
  defaultOpen: boolean;
  onHover: (id: string | null) => void;
  onPin?: (id: string | null) => void;
  onSelectEdge?: (edge: GraphEdge) => void;
}) {
  const [open, setOpen] = useState(defaultOpen);
  const label = (id: string) => graph.nodes.find((n) => n.id === id)?.label ?? id;
  const path = h.pathEdgeIds.map((id) => graph.edges.find((e) => e.id === id)).filter((e): e is GraphEdge => Boolean(e));
  const isQuery = graph.nodes.some((n) => n.id === h.diseaseId && n.isQueryDisease);
  return (
    <li
      onMouseEnter={() => onHover(h.id)}
      onMouseLeave={() => onHover(null)}
      className={`rounded-md border bg-white p-3 text-sm transition-colors ${pinned ? "border-blue-500 ring-1 ring-blue-500" : "border-zinc-200 hover:border-zinc-400"}`}
    >
      <div className="flex flex-wrap items-center gap-2">
        <StatusChip status={h.status} />
        <span className="text-[11px] uppercase tracking-wider text-zinc-500 [font-variant:small-caps]">{TEMPLATE[h.template]}</span>
        {isQuery && <span className="rounded bg-blue-50 px-1.5 py-0.5 text-[11px] text-blue-700">queried disease</span>}
        {onPin && (
          <button
            type="button"
            onClick={() => onPin(pinned ? null : h.id)}
            className="ml-auto text-[11px] text-zinc-500 hover:text-blue-700"
            title="Keep this path highlighted in the graph"
          >
            {pinned ? "unpin path" : "pin path"}
          </button>
        )}
      </div>
      <p className="mt-1.5 font-medium text-zinc-900">{h.statement}</p>

      <div className="mt-2 rounded border-l-2 border-emerald-500 bg-emerald-50/60 px-2 py-1 text-xs text-zinc-800">
        <span className="font-semibold text-emerald-900">Suggested test: </span>
        {h.suggestedTest}
      </div>

      <button type="button" onClick={() => setOpen(!open)} className="mt-2 text-xs font-medium text-zinc-600 hover:text-zinc-900" aria-expanded={open}>
        {open ? "▾" : "▸"} Evidence ladder ({h.ladder.length} rows, shown separately)
      </button>
      {open && (
        <ul className="mt-1 flex flex-col gap-1.5">
          {h.ladder.map((r, i) => (
            <li key={i} className="text-xs">
              <div className="flex items-start gap-2">
                <LadderBadge kind={r.kind} />
                <span className="text-zinc-600">
                  {r.label}: <span className="font-medium text-zinc-900">{r.value}</span>
                </span>
              </div>
              {r.sourceIds.length > 0 && <SourceChips ids={r.sourceIds} sources={sources} />}
            </li>
          ))}
        </ul>
      )}

      {path.length > 0 && (
        <div className="mt-2 flex flex-wrap items-center gap-1 text-[11px] text-zinc-600">
          <span className="text-zinc-500">Path:</span>
          {path.map((e) => (
            <button
              key={e.id}
              type="button"
              onClick={() => onSelectEdge?.(e)}
              title={`${label(e.from)} → ${label(e.to)}: ${e.label}`}
              className={`max-w-48 truncate rounded border px-1.5 py-0.5 hover:border-blue-500 hover:text-blue-700 ${
                e.kind === "absent" ? "border-dashed border-red-400 text-red-700" : "border-zinc-300"
              }`}
            >
              {STEP[e.type] ?? e.type} → {label(e.to)}
            </button>
          ))}
        </div>
      )}
      <div className="mt-1 text-[11px] text-zinc-500">Sources</div>
      <SourceChips ids={h.sourceIds} sources={sources} />
    </li>
  );
}
