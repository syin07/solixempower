// Repurposing block of the evidence report (KG_PLAN M4): Claude's claims about the hypotheses (they
// cite hyp:N plus the path records), then the code-generated hypotheses as a table — status, path,
// gap check, suggested test — so the report reads correctly even when the AI mentions only some.
import type { ReactNode } from "react";
import type { Hypothesis, ReportClaim, SourceRef } from "@/lib/contracts";
import { EvidenceBadge } from "./EvidenceBadge";
import { StatusChip, TEMPLATE } from "./HypothesisPanel";
import { SourceChips } from "./SourceChips";

export function ReportHypotheses({
  hypotheses,
  claims,
  sources,
  render,
}: {
  hypotheses: Hypothesis[];
  /** Report claims that cite a hyp:N id */
  claims: ReportClaim[];
  sources: Map<string, SourceRef>;
  render: (text: string) => ReactNode;
}) {
  if (!hypotheses.length && !claims.length) return null;
  return (
    <div className="mt-4 rounded-md border border-zinc-200 p-4">
      <h3 className="font-semibold text-zinc-900">Repurposing hypotheses</h3>
      <p className="mt-1 text-xs text-zinc-500">
        A repurposing hypothesis here is a traceable gap in public evidence, not a prediction of efficacy. The table is
        generated by code from the evidence graph; the claims above it are Claude&apos;s summary of the same rows.
      </p>

      {claims.length > 0 && (
        <ul className="mt-3 flex flex-col gap-2.5">
          {claims.map((c, i) => (
            <li key={i} className="text-sm">
              <div className="flex items-start gap-2">
                <EvidenceBadge kind={c.kind} />
                <span className="text-zinc-800">{render(c.text)}</span>
              </div>
              <SourceChips ids={c.sourceIds} sources={sources} />
            </li>
          ))}
        </ul>
      )}

      {hypotheses.length > 0 && (
        <div className="mt-3 overflow-x-auto">
          <table className="w-full min-w-[640px] border-collapse text-left text-xs">
            <thead>
              <tr className="border-b border-zinc-200 text-zinc-500">
                <th className="py-1.5 pr-2 font-medium">#</th>
                <th className="py-1.5 pr-2 font-medium">Hypothesis</th>
                <th className="py-1.5 pr-2 font-medium">Status</th>
                <th className="py-1.5 pr-2 font-medium">Gap check</th>
                <th className="py-1.5 pr-2 font-medium">Suggested test</th>
                <th className="py-1.5 font-medium">Sources</th>
              </tr>
            </thead>
            <tbody>
              {hypotheses.map((h) => {
                const gap = h.ladder.find((r) => r.label === "Gap check");
                return (
                  <tr key={h.id} id={h.id.replace(":", "-")} className="scroll-mt-20 border-b border-zinc-100 align-top target:bg-emerald-50">
                    <td className="py-2 pr-2 font-mono text-zinc-500">{h.id}</td>
                    <td className="py-2 pr-2 text-zinc-900">
                      {h.statement}
                      <div className="text-[11px] uppercase tracking-wider text-zinc-500">{TEMPLATE[h.template]}</div>
                    </td>
                    <td className="py-2 pr-2">
                      <StatusChip status={h.status} />
                    </td>
                    <td className="py-2 pr-2 text-zinc-700">{gap ? render(gap.value) : "—"}</td>
                    <td className="py-2 pr-2 text-zinc-700">{render(h.suggestedTest)}</td>
                    <td className="py-2">
                      <SourceChips ids={h.sourceIds} sources={sources} />
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}
